def img2file(code_list, img_file):
    # 设置每行显示数量
    cols = 8
    # 计算行数
    rows = (len(code_list) + cols - 1) // cols

    # 图片参数
    font_size = 28
    cell_width = 140
    cell_height = 50
    padding = 20

    img_width = cols * cell_width + 2 * padding
    img_height = rows * cell_height + 2 * padding

    # 创建白底图片
    img = Image.new('RGB', (img_width, img_height), 'white')
    draw = ImageDraw.Draw(img)

    # 尝试加载中文字体，若无则使用默认字体
    try:
        font = ImageFont.truetype("simhei.ttf", font_size)
    except:
        font = ImageFont.load_default()

    # 绘制股票代码
    for i, code in enumerate(code_list):
        row = i // cols
        col = i % cols
        x = padding + col * cell_width
        y = padding + row * cell_height
        draw.text((x, y), code, fill='black', font=font)
    img_path = os.path.join('/Users/houjie/Desktop', img_file)
    img.save(img_path, 'PNG', optimize=True)
    size_kb = os.path.getsize(img_path) / 1024
    print(f"图片已生成：{img_file}，大小约 {size_kb:.1f} KB，清晰度较高")

